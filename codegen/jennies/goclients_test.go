package jennies

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/grafana/grafana-app-sdk/codegen"
)

func TestClientJenny_responseType(t *testing.T) {
	goKind := func(name string, enabled bool) codegen.VersionedKind {
		kind := codegen.VersionedKind{Kind: name}
		kind.Codegen.Go.Enabled = enabled
		return kind
	}
	version := &codegen.SimpleVersion{VersionProperties: codegen.VersionProperties{Name: "v1"}, AllKinds: []codegen.VersionedKind{goKind("Thing", true), goKind("Other", true), goKind("NoGo", false)}}

	t.Run("a route generates its response type", func(t *testing.T) {
		got, err := (&ClientJenny{}).responseType(version, "")(codegen.CustomRoute{Name: "addStar"})
		require.NoError(t, err)
		assert.Equal(t, "AddStarResponse", got)
	})
	t.Run("a route returns the type of a kind, which it does not generate", func(t *testing.T) {
		got, err := (&ClientJenny{}).responseType(version, "")(codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.NoError(t, err)
		assert.Equal(t, "Thing", got)
	})
	t.Run("a kind route returns the type of its own kind when generated by kind", func(t *testing.T) {
		got, err := (&ClientJenny{GroupByKind: true}).responseType(version, "Thing")(codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.NoError(t, err)
		assert.Equal(t, "Thing", got)
	})
	t.Run("a type of another package is not available when generated by kind", func(t *testing.T) {
		_, err := (&ClientJenny{GroupByKind: true}).responseType(version, "Thing")(codegen.CustomRoute{Name: "getLatest", ResponseKind: "Other"})
		require.ErrorContains(t, err, "whose type is not in its package when generating by kind")
		_, err = (&ClientJenny{GroupByKind: true}).responseType(version, "")(codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.ErrorContains(t, err, "whose type is not in its package when generating by kind")
	})
	t.Run("a kind that does not generate Go has no type to return", func(t *testing.T) {
		_, err := (&ClientJenny{}).responseType(version, "")(codegen.CustomRoute{Name: "getLatest", ResponseKind: "NoGo"})
		require.ErrorContains(t, err, "does not generate Go code")
	})
}
