package jennies

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/grafana/grafana-app-sdk/codegen"
	"github.com/grafana/grafana-app-sdk/codegen/templates"
)

func TestClientJenny_responseType(t *testing.T) {
	goKind := func(name string, enabled bool) codegen.VersionedKind {
		kind := codegen.VersionedKind{Kind: name, MachineName: strings.ToLower(name)}
		kind.Codegen.Go.Enabled = enabled
		return kind
	}
	version := &codegen.SimpleVersion{VersionProperties: codegen.VersionProperties{Name: "v1"}, AllKinds: []codegen.VersionedKind{goKind("Thing", true), goKind("Other", true), goKind("NoGo", false)}}

	manifest := &codegen.SimpleManifest{AppManifestProperties: codegen.AppManifestProperties{Group: "stars"}}
	respond := func(j *ClientJenny, owner string, route codegen.CustomRoute) (string, *templates.GoImport, error) {
		return j.responseType(manifest, version, owner)(route)
	}

	t.Run("a route generates its response type", func(t *testing.T) {
		got, imp, err := respond(&ClientJenny{}, "", codegen.CustomRoute{Name: "addStar"})
		require.NoError(t, err)
		assert.Equal(t, "AddStarResponse", got)
		assert.Nil(t, imp)
	})
	t.Run("a route returns the type of a kind, which it does not generate", func(t *testing.T) {
		got, imp, err := respond(&ClientJenny{}, "", codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.NoError(t, err)
		assert.Equal(t, "Thing", got)
		assert.Nil(t, imp)
	})
	t.Run("a kind route returns the type of its own kind when generated by kind", func(t *testing.T) {
		got, imp, err := respond(&ClientJenny{GroupByKind: true}, "Thing", codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.NoError(t, err)
		assert.Equal(t, "Thing", got)
		assert.Nil(t, imp)
	})
	t.Run("the type of another package is imported when generated by kind", func(t *testing.T) {
		jenny := &ClientJenny{GroupByKind: true, ProjectRepo: "example.com/app", GoGenPath: "pkg/generated"}
		for _, owner := range []string{"", "Other"} {
			got, imp, err := respond(jenny, owner, codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
			require.NoError(t, err)
			assert.Equal(t, "thingv1.Thing", got)
			assert.Equal(t, &templates.GoImport{Alias: "thingv1", Path: "example.com/app/pkg/generated/thing/v1"}, imp)
		}
	})
	t.Run("the type of another package needs the Go module to import it from", func(t *testing.T) {
		_, _, err := respond(&ClientJenny{GroupByKind: true}, "", codegen.CustomRoute{Name: "getLatest", ResponseKind: "Thing"})
		require.ErrorContains(t, err, "which is not set")
	})
	t.Run("a kind that does not generate Go has no type to return", func(t *testing.T) {
		_, _, err := respond(&ClientJenny{}, "", codegen.CustomRoute{Name: "getLatest", ResponseKind: "NoGo"})
		require.ErrorContains(t, err, "does not generate Go code")
	})
}
